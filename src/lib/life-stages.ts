/** 对外结构: 保留 sections（通用+专属, 供筛选用）, 另给 own（专属, 供展示口径用） */
export const LIFE_STAGES: Record<string, StageDef & { sections: number[] }> = Object.fromEntries(
  Object.entries(RAW).map(([key, stage]) => [
    key,
    { ...stage, sections: [...UNIVERSAL_SECTIONS, ...stage.own].sort((a, b) => a - b) },
  ]),
);

export function getLifeStage(stage: string) {
  return LIFE_STAGES[stage];
}
